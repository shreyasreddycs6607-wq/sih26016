package com.focusforce.app.data.social

import android.app.Activity
import android.content.Context
import androidx.credentials.ClearCredentialStateRequest
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import com.focusforce.app.domain.social.AuthService
import com.focusforce.app.domain.social.AuthUser
import com.focusforce.app.domain.social.FailReason
import com.focusforce.app.domain.social.SocialResult
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.android.libraries.identity.googleid.GoogleIdTokenParsingException
import com.google.firebase.Firebase
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.FirebaseAuthRecentLoginRequiredException
import com.google.firebase.auth.GoogleAuthProvider
import com.google.firebase.auth.auth
import dagger.hilt.android.qualifiers.ApplicationContext
import javax.inject.Inject
import javax.inject.Singleton
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.channels.awaitClose
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.callbackFlow
import kotlinx.coroutines.flow.distinctUntilChanged
import kotlinx.coroutines.tasks.await

/**
 * Google sign-in through Credential Manager, exchanged for a Firebase Auth user. Only works once the owner has added
 * google-services.json (see PHASE6.md); without it [SocialModule] never selects this class.
 */
@Singleton
class FirebaseAuthService @Inject constructor(
    @ApplicationContext private val context: Context,
) : AuthService {

    private val auth: FirebaseAuth get() = Firebase.auth

    override val available = true

    override val user: Flow<AuthUser?> = callbackFlow {
        val listener = FirebaseAuth.AuthStateListener { trySend(it.currentUser?.let { u -> AuthUser(u.uid, u.displayName) }) }
        auth.addAuthStateListener(listener)
        awaitClose { auth.removeAuthStateListener(listener) }
    }.distinctUntilChanged()

    override suspend fun signIn(activity: Activity): SocialResult<AuthUser> {
        // default_web_client_id is generated by the google-services plugin; look it up by name so this compiles without it.
        val resId = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
        if (resId == 0) return SocialResult.Fail(FailReason.NOT_AVAILABLE)
        return try {
            val option = GetGoogleIdOption.Builder()
                .setFilterByAuthorizedAccounts(false)
                .setServerClientId(context.getString(resId))
                .build()
            val request = GetCredentialRequest.Builder().addCredentialOption(option).build()
            val credential = CredentialManager.create(activity).getCredential(activity, request).credential
            if (credential !is CustomCredential || credential.type != GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                return SocialResult.Fail(FailReason.INVALID)
            }
            val google = GoogleIdTokenCredential.createFrom(credential.data)
            val result = auth.signInWithCredential(GoogleAuthProvider.getCredential(google.idToken, null)).await()
            val u = result.user ?: return SocialResult.Fail(FailReason.NETWORK)
            SocialResult.Ok(AuthUser(u.uid, u.displayName))
        } catch (e: CancellationException) {
            throw e
        } catch (_: GetCredentialCancellationException) {
            SocialResult.Fail(FailReason.CANCELLED)
        } catch (_: GetCredentialException) {
            SocialResult.Fail(FailReason.DENIED)
        } catch (_: GoogleIdTokenParsingException) {
            SocialResult.Fail(FailReason.INVALID)
        } catch (_: Exception) {
            SocialResult.Fail(FailReason.NETWORK)
        }
    }

    override suspend fun signOut() {
        auth.signOut()
        runCatching { CredentialManager.create(context).clearCredentialState(ClearCredentialStateRequest()) }
    }

    override suspend fun deleteAccount(): SocialResult<Unit> = try {
        auth.currentUser?.delete()?.await()
        SocialResult.Ok(Unit)
    } catch (e: CancellationException) {
        throw e
    } catch (_: FirebaseAuthRecentLoginRequiredException) {
        SocialResult.Fail(FailReason.DENIED)
    } catch (_: Exception) {
        SocialResult.Fail(FailReason.NETWORK)
    }
}
